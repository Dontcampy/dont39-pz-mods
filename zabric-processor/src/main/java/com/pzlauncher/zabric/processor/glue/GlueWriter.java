package com.pzlauncher.zabric.processor.glue;

import com.pzlauncher.zabric.processor.glue.GlueModel.At;
import com.pzlauncher.zabric.processor.glue.GlueModel.Block;
import com.pzlauncher.zabric.processor.glue.GlueModel.Call;
import com.pzlauncher.zabric.processor.glue.GlueModel.Patch;
import com.pzlauncher.zabric.processor.glue.GlueModel.Share;
import com.pzlauncher.zabric.processor.glue.GlueModel.Value;
import com.pzlauncher.zabric.processor.glue.HookDecls.Kind;

import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

/**
 * Writes a {@link GlueModel.Unit}'s glue source and listings, in the shape of Zabric's reference glue
 * ({@code zabric/src/test/java/com/pzlauncher/zabric/hook/weave/glue/WeaveGlue.java}).
 */
public final class GlueWriter {
    private static final int WIDTH = 120;
    private static final String INDENT = "    ";

    private GlueWriter() {
    }

    public static String listingPath(String hookClassBinaryName) {
        return Names.LISTING_DIR + hookClassBinaryName + Names.LISTING_SUFFIX;
    }

    /** By resource path. */
    public static Map<String, String> listings(GlueModel.Unit unit) {
        Map<String, String> listings = new LinkedHashMap<>();
        for (GlueModel.Listing listing : unit.listings()) {
            StringBuilder text = new StringBuilder(Names.LISTING_HEADER).append('\n');
            text.append("mod ").append(unit.modId()).append('\n');
            text.append("gate ").append(listing.gate()).append('\n');
            listing.patches().forEach(p -> text.append("patch ").append(unit.binaryName(p)).append('\n'));
            listing.patches().forEach(p -> text.append("hook ").append(p.target().owner()).append(' ')
                    .append(p.target().method()).append(' ').append(p.target().descriptor()).append(' ')
                    .append(unit.binaryName(p)).append('\n'));
            listings.put(listingPath(listing.hookClass()), text.toString());
        }
        return listings;
    }

    public static String source(GlueModel.Unit unit) {
        Out out = new Out();
        out.line(0, "package " + unit.packageName() + ";");
        out.blank();
        for (String name : List.of(Names.CALLBACK_INFO, Names.CALLBACK_INFO_RETURNABLE, Names.LOCAL_REF,
                Names.MOD_HOOKS, Names.ZABRIC_HOOKS, Names.PATCH)) {
            out.line(0, "import " + name + ";");
        }
        out.blank();
        out.line(0, "// Generated by zabric-processor. Do not edit.");
        out.line(0, "public final class " + unit.className() + " {");
        out.line(1, "public static final ModHooks MOD = ZabricHooks.mod(" + literal(unit.modId()) + ");");
        out.blank();
        out.line(1, "private " + unit.className() + "() {");
        out.line(1, "}");
        for (Patch patch : unit.patches()) {
            out.blank();
            new PatchWriter(out, patch).write();
        }
        out.line(0, "}");
        return out.toString();
    }

    private static final class PatchWriter {
        private final Out out;
        private final Patch patch;
        private final GlueModel.Target target;
        private final boolean nonVoid;
        private final boolean cancellableHead;
        private final boolean hasFinally;
        private final boolean hasReturn;

        PatchWriter(Out out, Patch patch) {
            this.out = out;
            this.patch = patch;
            this.target = patch.target();
            this.nonVoid = !target.isVoid();
            List<Call> calls = patch.blocks().stream().flatMap(b -> b.calls().stream()).toList();
            this.cancellableHead = calls.stream().anyMatch(c -> c.at() == At.HEAD && c.cancellable());
            this.hasFinally = calls.stream().anyMatch(c -> c.at() == At.FINALLY);
            this.hasReturn = calls.stream().anyMatch(c -> c.at() == At.RETURN);
        }

        void write() {
            String name = patch.name();
            out.line(1, "@Patch(className = " + literal(target.owner()) + ", methodName = "
                    + literal(target.method()) + ", strictMatch = true)");
            out.line(1, "public static final class " + name + " {");
            out.line(2, "private " + name + "() {");
            out.line(2, "}");
            out.blank();
            enter();
            boolean hasExit = hasFinally || hasReturn || cancellableHead && nonVoid;
            if (hasExit) {
                out.blank();
                exit();
            }
            out.line(1, "}");
        }

        private void enter() {
            List<Call> heads = patch.blocks().stream().flatMap(b -> b.calls().stream())
                    .filter(c -> c.at() == At.HEAD).toList();
            List<String> params = new ArrayList<>();
            if (heads.stream().anyMatch(c -> c.uses(Value.Kind.SELF))) {
                params.add("@Patch.This " + target.ownerSource() + " self");
            }
            for (int k = 0; k < target.args().size(); k++) {
                GlueModel.Arg arg = target.args().get(k);
                String binding = arg.writable() ? "@Patch.Argument(value = " + k + ", readOnly = false)"
                        : "@Patch.Argument(" + k + ")";
                params.add(binding + " " + arg.binding() + " arg" + k);
            }
            for (int n = 0; n < patch.blocks().size(); n++) {
                Block block = patch.blocks().get(n);
                params.add(local(gateLocal(n, block), "boolean"));
                for (Share share : block.shares()) {
                    params.add(local(shareLocal(n, share.key()), "LocalRef<" + share.type() + ">"));
                }
            }
            if (cancellableHead) {
                params.add(local("cancelled", "boolean"));
                if (nonVoid) {
                    params.add(local("value", target.returnType()));
                }
            }
            out.line(2, cancellableHead ? "@Patch.OnEnter(skipOn = true)" : "@Patch.OnEnter");
            header(cancellableHead ? "boolean" : "void", "enter", params);
            for (int n = 0; n < patch.blocks().size(); n++) {
                Block block = patch.blocks().get(n);
                String gate = block.always() ? "MOD.open()" : "MOD.active(" + block.gate() + ")";
                out.line(3, gateLocal(n, block) + " = " + gate + ";");
            }
            for (int n = 0; n < patch.blocks().size(); n++) {
                Block block = patch.blocks().get(n);
                List<Call> own = block.calls().stream().filter(c -> c.at() == At.HEAD).toList();
                if (own.isEmpty() && block.shares().isEmpty()) {
                    continue;
                }
                out.line(3, "if (" + gateLocal(n, block) + ") {");
                for (Share share : block.shares()) {
                    out.line(4, shareLocal(n, share.key()) + " = LocalRef.create();");
                }
                for (Call call : own) {
                    guarded(4, n, block, call);
                }
                out.line(3, "}");
            }
            if (cancellableHead) {
                out.line(3, "return false;");
            }
            out.line(2, "}");
        }

        private void exit() {
            List<Call> exits = patch.blocks().stream().flatMap(b -> b.calls().stream()).filter(Call::exits).toList();
            boolean retWritable = cancellableHead || exits.stream().anyMatch(c -> c.kind() == Kind.MODIFY_RETURN_VALUE
                    || c.at() == At.RETURN && c.cancellable());
            boolean readCancelled = cancellableHead && (nonVoid || hasReturn);
            boolean readValue = cancellableHead && nonVoid;
            List<String> params = new ArrayList<>();
            if (exits.stream().anyMatch(c -> c.uses(Value.Kind.SELF))) {
                params.add("@Patch.This " + target.ownerSource() + " self");
            }
            for (int k = 0; k < target.args().size(); k++) {
                params.add("@Patch.Argument(" + k + ") " + target.args().get(k).binding() + " arg" + k);
            }
            if (nonVoid) {
                params.add((retWritable ? "@Patch.Return(readOnly = false) " : "@Patch.Return ")
                        + target.returnType() + " ret");
            }
            if (hasFinally) {
                params.add("@Patch.Thrown Throwable thrown");
            }
            for (int n = 0; n < patch.blocks().size(); n++) {
                Block block = patch.blocks().get(n);
                List<Call> own = block.calls().stream().filter(Call::exits).toList();
                if (own.isEmpty()) {
                    continue;
                }
                params.add(local(gateLocal(n, block), "boolean"));
                for (Share share : block.shares()) {
                    if (own.stream().anyMatch(c -> c.values().contains(new Value(Value.Kind.SHARE, -1, share.key())))) {
                        params.add(local(shareLocal(n, share.key()), "LocalRef<" + share.type() + ">"));
                    }
                }
            }
            if (readCancelled) {
                params.add(local("cancelled", "boolean"));
            }
            if (readValue) {
                params.add(local("value", target.returnType()));
            }
            out.line(2, hasFinally ? "@Patch.OnExit(onThrowable = Throwable.class)" : "@Patch.OnExit");
            header("void", "exit", params);
            if (hasReturn) {
                List<String> done = new ArrayList<>();
                if (cancellableHead) {
                    done.add("cancelled");
                }
                if (hasFinally) {
                    done.add("thrown != null");
                }
                out.line(3, "boolean done = " + (done.isEmpty() ? "false" : String.join(" || ", done)) + ";");
            }
            if (readValue) {
                out.line(3, "if (cancelled) {");
                out.line(4, "ret = value;");
                out.line(3, "}");
            }
            for (int n = 0; n < patch.blocks().size(); n++) {
                Block block = patch.blocks().get(n);
                for (Call call : block.calls()) {
                    if (!call.exits()) {
                        continue;
                    }
                    String gate = gateLocal(n, block) + (call.at() == At.RETURN ? " && !done" : "");
                    out.line(3, "if (" + gate + ") {");
                    guarded(4, n, block, call);
                    out.line(3, "}");
                }
            }
            out.line(2, "}");
        }

        private void header(String returnType, String name, List<String> params) {
            out.line(2, "public static " + returnType + " " + name + "(");
            for (int i = 0; i < params.size(); i++) {
                out.line(4, params.get(i) + (i == params.size() - 1 ? ") {" : ","));
            }
        }

        private void guarded(int level, int n, Block block, Call call) {
            out.line(level, "try {");
            call(level + 1, n, block, call);
            out.line(level, "} catch (Throwable t) {");
            String what = "running " + block.hookClass() + "." + call.handler() + " on " + target.owner() + "."
                    + target.method();
            out.call(level + 1, "MOD.failed(", List.of(block.gate(), literal(what), "t"), ");");
            out.line(level, "}");
        }

        private void call(int level, int n, Block block, Call call) {
            String callee = block.callee() + "." + call.handler() + "(";
            if (call.kind() == Kind.MODIFY_RETURN_VALUE) {
                out.call(level, "ret = " + callee, values(n, call, null), ");");
                return;
            }
            if (call.kind() == Kind.MODIFY_VARIABLE) {
                out.call(level, "arg" + call.modifiedArg() + " = " + callee, values(n, call, null), ");");
                return;
            }
            String id = literal(target.method());
            String cancellable = Boolean.toString(call.cancellable());
            boolean returnable = call.returnable() != null;
            boolean variable = call.cancellable() || returnable && call.at() != At.HEAD;
            String callback;
            if (!returnable) {
                callback = "new CallbackInfo(" + id + ", " + cancellable + ")";
                if (variable) {
                    out.line(level, "CallbackInfo ci = " + callback + ";");
                }
            } else if (variable) {
                List<String> args = new ArrayList<>(List.of(id, cancellable));
                if (call.at() == At.RETURN) {
                    args.add("ret");
                } else if (call.at() == At.FINALLY) {
                    // a conditional among the constructor's arguments fails verification once inlined, and ZombieBuddy
                    // then drops every patch of the target class silently
                    out.line(level, call.returnable() + " returned = null;");
                    out.line(level, "if (thrown == null) {");
                    out.line(level + 1, "returned = ret;");
                    out.line(level, "}");
                    args.add("returned");
                }
                out.call(level, "CallbackInfoReturnable<" + call.returnable() + "> ci = new CallbackInfoReturnable<>(",
                        args, ");");
                callback = null;
            } else {
                callback = "new CallbackInfoReturnable<" + call.returnable() + ">(" + id + ", " + cancellable + ")";
            }
            out.call(level, callee, values(n, call, variable ? "ci" : callback), ");");
            if (!call.cancellable()) {
                return;
            }
            out.line(level, "if (ci.isCancelled()) {");
            String getter = "ci.getReturnValue" + Names.GETTER_SUFFIXES.getOrDefault(target.returnType(), "") + "()";
            if (call.at() == At.HEAD) {
                if (nonVoid) {
                    out.line(level + 1, "value = " + getter + ";");
                }
                out.line(level + 1, "cancelled = true;");
                out.line(level + 1, "return true;");
            } else {
                if (nonVoid) {
                    out.line(level + 1, "ret = " + getter + ";");
                }
                out.line(level + 1, "done = true;");
            }
            out.line(level, "}");
        }

        private List<String> values(int n, Call call, String callback) {
            List<String> values = new ArrayList<>();
            for (Value value : call.values()) {
                values.add(switch (value.kind()) {
                    case SELF -> "self";
                    case ARG -> {
                        GlueModel.Arg arg = target.args().get(value.index());
                        String name = "arg" + value.index();
                        yield arg.binding().equals(arg.type()) ? name : "(" + arg.type() + ") " + name;
                    }
                    case CALLBACK -> callback;
                    case THROWN -> "thrown";
                    case SHARE -> shareLocal(n, value.key());
                    case ORIGINAL -> call.kind() == Kind.MODIFY_RETURN_VALUE ? "ret" : "arg" + call.modifiedArg();
                });
            }
            return values;
        }
    }

    private static String gateLocal(int n, Block block) {
        return "h" + n + (block.always() ? "$open" : "$active");
    }

    private static String shareLocal(int n, String key) {
        return "h" + n + "$share$" + key;
    }

    private static String local(String name, String type) {
        return "@Patch.Local(\"" + name + "\") " + type + " " + name;
    }

    private static String literal(String text) {
        return "\"" + text.replace("\\", "\\\\").replace("\"", "\\\"") + "\"";
    }

    /** Wraps call arguments greedily at {@link #WIDTH}. */
    private static final class Out {
        private final StringBuilder text = new StringBuilder();

        void line(int level, String line) {
            text.append(INDENT.repeat(level)).append(line).append('\n');
        }

        void blank() {
            text.append('\n');
        }

        void call(int level, String head, List<String> args, String tail) {
            StringBuilder line = new StringBuilder(INDENT.repeat(level)).append(head);
            if (args.isEmpty()) {
                line.append(tail);
            }
            for (int i = 0; i < args.size(); i++) {
                String piece = args.get(i) + (i == args.size() - 1 ? tail : ",");
                if (i == 0) {
                    line.append(piece);
                } else if (line.length() + 1 + piece.length() > WIDTH) {
                    text.append(line).append('\n');
                    line = new StringBuilder(INDENT.repeat(level + 2)).append(piece);
                } else {
                    line.append(' ').append(piece);
                }
            }
            text.append(line).append('\n');
        }

        @Override
        public String toString() {
            return text.toString();
        }
    }
}
