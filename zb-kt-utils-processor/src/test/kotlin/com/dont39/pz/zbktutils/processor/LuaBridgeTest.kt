package com.dont39.pz.zbktutils.processor

import org.junit.jupiter.api.Assertions.assertEquals
import org.junit.jupiter.api.Test
import org.junit.jupiter.api.io.TempDir
import java.io.File

class LuaBridgeTest {
  @TempDir
  lateinit var dir: File

  // the game's annotation, which the bridge names
  private val luaMethod = java(
    "LuaMethod.java",
    """
    package se.krka.kahlua.integration.annotations;

    public @interface LuaMethod {
        String name();

        boolean global() default false;
    }
    """,
  )

  private fun compile(functions: String) = ksp(
    dir,
    luaMethod,
    kotlin("Lua.kt", "package l\n\nimport com.dont39.pz.zbktutils.glue.LuaGlobal\n\n" + functions.trimIndent()),
  )

  @Test
  fun bridge() {
    val result = compile(
      """
      @LuaGlobal("test_top")
      fun top(name: String?, count: Int): Boolean = name != null && count > 0

      object Api {
        @LuaGlobal("test_list")
        fun list(extra: Map<String, *>?): Array<String>? = null

        @LuaGlobal("test_run")
        internal fun run() {}
      }
      """,
    )
    result.assertCompiles()
    assertEquals(
      """
      // Generated by zb-kt-utils-processor from @LuaGlobal. Do not edit.
      package glue

      import se.krka.kahlua.integration.annotations.LuaMethod

      // ZombieBuddy exposes global Lua functions only from classes in exactly javaPkgName; Kahlua calls
      // them on an instance ZombieBuddy creates through the private constructor.
      object TestLua {
        @LuaMethod(name = "test_list", global = true)
        fun test_list(extra: kotlin.collections.Map<kotlin.String, *>?): kotlin.Array<kotlin.String>? {
          return l.Api.list(extra)
        }

        @LuaMethod(name = "test_run", global = true)
        fun test_run() {
          l.Api.run()
        }

        @LuaMethod(name = "test_top", global = true)
        fun test_top(name: kotlin.String?, count: kotlin.Int): kotlin.Boolean {
          return l.top(name, count)
        }
      }

      """.trimIndent(),
      result.generated["kotlin/glue/TestLua.kt"],
    )
    assertEquals(
      "lua glue.TestLua\nluaGlobal test_list\nluaGlobal test_run\nluaGlobal test_top\n",
      result.generated["resources/META-INF/zbkt/glue/Test.txt"],
    )
  }

  @Test
  fun names() {
    val result = compile(
      """
      @LuaGlobal("test_bad-name")
      fun badName() {}

      @LuaGlobal("other_x")
      fun otherPrefix() {}

      @LuaGlobal("test_")
      fun onlyPrefix() {}

      @LuaGlobal("test_dup")
      fun first() {}

      @LuaGlobal("test_dup")
      fun second() {}
      """,
    )
    result.assertError("badName: Lua name \"test_bad-name\" is not a Lua identifier")
    val prefix = "must start with \"test_\" (Lua globals are shared by all mods)"
    result.assertError("otherPrefix: Lua name \"other_x\" $prefix")
    result.assertError("onlyPrefix: Lua name \"test_\" $prefix")
    result.assertError("second: Lua name \"test_dup\" is already used by first")
  }

  @Test
  fun functions() {
    val result = compile(
      """
      @LuaGlobal("test_varargs")
      fun varargs(vararg s: String) {}

      @LuaGlobal("test_ext")
      fun String.ext() {}

      @LuaGlobal("test_generic")
      fun <X> generic() {}

      @LuaGlobal("test_suspend")
      suspend fun suspending() {}

      @LuaGlobal("test_private")
      private fun hidden() {}
      """,
    )
    result.assertError("varargs: vararg parameters are not supported")
    result.assertError("ext: @LuaGlobal cannot be on an extension function")
    result.assertError("generic: @LuaGlobal cannot be on a generic function")
    result.assertError("suspending: @LuaGlobal cannot be on a suspend function")
    result.assertError("hidden: @LuaGlobal needs a public or internal function (the generated bridge calls it)")
  }

  @Test
  fun owners() {
    val result = compile(
      """
      class C {
        @LuaGlobal("test_member")
        fun member() {}

        companion object {
          @LuaGlobal("test_companion")
          fun companionMember() {}
        }
      }

      object O {
        object N {
          @LuaGlobal("test_nested")
          fun nested() {}
        }
      }

      private object P {
        @LuaGlobal("test_privateObject")
        fun inPrivate() {}
      }
      """,
    )
    val owner = "@LuaGlobal needs a member of a top-level object or a top-level function (the generated bridge calls " +
      "it without a receiver); not a class or companion member, nested or local function"
    result.assertError("C.member: $owner")
    result.assertError("Companion.companionMember: $owner")
    result.assertError("N.nested: $owner")
    result.assertError("P.inPrivate: @LuaGlobal needs a public or internal object (the generated bridge calls it)")
  }
}
