"""Writes a generated depth-map batch and order_greedy's order for it (4 and 2 workers) as Schedule test data.

Usage: python -I gen_greedy.py <this research dir> faster-loading/src/test/resources/com/dont39/pz/fasterloading/depth/greedy-batch.txt
"""
import random
import sys

sys.path.insert(0, sys.argv[1])
import reprioritise_sim as sim

rng = random.Random(42)
# chain names sort in queue order, as Schedule breaks ties by first appearance and the simulator's heap by name
lengths = [144, 116, 102, 55, 32, 28, 27, 9, 4, 1, 216]
base, inst, est = [], {}, {}
for c, n in enumerate(lengths):
    for _ in range(n):
        t = len(base)
        base.append(t)
        inst[t] = 'c%02d' % c
        est[t] = rng.choice([0, 1, 2, 4, 8, 8, 16, 16, 32, 64])
out = ['# generated by .trellis/tasks/10-22-depth-map-speedup/research/gen_greedy.py from reprioritise_sim.py'
       ' order_greedy(largest_first=False), seed 42',
       '# task <chain> <cost>, in queue order; order <workers> <tasks in emitted order>']
for t in base:
    out.append('task %d %d' % (int(inst[t][1:]), est[t]))
for w in (4, 2):
    sim.WORKERS = w
    out.append('order %d %s' % (w, ' '.join(map(str, sim.order_greedy(base, inst, est, False)))))
open(sys.argv[2], 'w', newline='\n').write('\n'.join(out) + '\n')
